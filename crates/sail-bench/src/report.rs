//! Generates `docs/benchmarks.md` from `bench/results/*.json`. The output is
//! derived data and is never edited by hand (charter: "Publish results in a
//! generated `docs/benchmarks.md` from machine-readable data").

use std::fmt::Write as _;

use crate::cold::{BenchFile, UnitResult, median};

fn ms(x: f64) -> String {
    if x >= 10_000.0 {
        format!("{:.1} s", x / 1000.0)
    } else {
        format!("{x:.0} ms")
    }
}

fn pct(sail: f64, plain: f64) -> String {
    if plain > 0.0 {
        format!("{:+.1}%", (sail - plain) / plain * 100.0)
    } else {
        "n/a".to_owned()
    }
}

#[allow(clippy::cast_precision_loss)] // sample counts and byte sizes, for display
fn mean_u64(xs: &[u64]) -> Option<f64> {
    (!xs.is_empty()).then(|| xs.iter().sum::<u64>() as f64 / xs.len() as f64)
}

#[allow(clippy::cast_precision_loss)] // byte counts, for display
fn mb(bytes: u64) -> String {
    format!("{:.0} MB", bytes as f64 / 1_048_576.0)
}

struct Totals {
    plain: f64,
    sail: f64,
    smt: f64,
    functions: usize,
    same: usize,
    different: usize,
    infra: usize,
}

fn totals(units: &[UnitResult]) -> Totals {
    let mut t = Totals {
        plain: 0.0,
        sail: 0.0,
        smt: 0.0,
        functions: 0,
        same: 0,
        different: 0,
        infra: 0,
    };
    for u in units {
        t.plain += median(&u.plain.wall_ms).unwrap_or(0.0);
        t.sail += median(&u.sail.wall_ms).unwrap_or(0.0);
        t.smt += mean_u64(&u.plain.smt_ms).unwrap_or(0.0);
        t.functions += u.functions;
        t.same += u.same;
        t.different += u.different;
        t.infra += u.infra_errors;
    }
    t
}

/// Renders the Markdown page for `files` (each from one `cold` run).
#[must_use]
pub fn render(files: &[(String, BenchFile)]) -> String {
    let mut out = String::new();
    let _ = writeln!(
        out,
        "# Benchmarks\n\n<!-- Generated by `sail-bench report` from bench/results/*.json. Do not edit. -->\n"
    );
    let _ = writeln!(
        out,
        "Every benchmark round also runs the conformance comparison (charter: a speedup that coincides with any verdict difference is a bug, not a result). Times are medians over rounds. Units run one at a time.\n"
    );
    for (name, f) in files {
        let t = totals(&f.units);
        let _ = writeln!(
            out,
            "## `{name}`: {} workload, {} tier\n",
            f.workload, f.tier
        );
        let _ = writeln!(
            out,
            "- Verus {}, Z3 {}, sail `{}`; {} round(s) per unit",
            f.verus_release, f.z3_version, f.sail_commit, f.rounds
        );
        let machine: Vec<String> = f.machine.iter().map(|(k, v)| format!("{k}: {v}")).collect();
        let _ = writeln!(out, "- Machine: {}\n", machine.join("; "));
        let _ = writeln!(
            out,
            "| Measure | Plain Verus | sail (pass-through) | Change |\n|---|---|---|---|"
        );
        let _ = writeln!(out, "| Units | {} | {} | |", f.units.len(), f.units.len());
        let _ = writeln!(out, "| Functions | {} | {} | |", t.functions, t.functions);
        let _ = writeln!(
            out,
            "| Total wall time (sum of unit medians) | {} | {} | {} |",
            ms(t.plain),
            ms(t.sail),
            pct(t.sail, t.plain)
        );
        let share = if t.plain > 0.0 {
            t.smt / t.plain * 100.0
        } else {
            0.0
        };
        let _ = writeln!(
            out,
            "| Solver time reported by Verus (mean) | {} ({share:.0}% of wall) | | |",
            ms(t.smt)
        );
        let _ = writeln!(
            out,
            "| Conformance (rounds) | | {} same, {} different, {} infra errors | |\n",
            t.same, t.different, t.infra
        );
        let mut slow: Vec<&UnitResult> = f.units.iter().collect();
        slow.sort_by(|a, b| {
            median(&b.plain.wall_ms)
                .unwrap_or(0.0)
                .total_cmp(&median(&a.plain.wall_ms).unwrap_or(0.0))
        });
        let _ = writeln!(
            out,
            "Slowest units:\n\n| Unit | Functions | Plain | sail | Change | Solver time | Peak RSS |\n|---|---:|---:|---:|---:|---:|---:|"
        );
        for u in slow.iter().take(10) {
            let (p, s) = (
                median(&u.plain.wall_ms).unwrap_or(0.0),
                median(&u.sail.wall_ms).unwrap_or(0.0),
            );
            let rss = u
                .plain
                .max_rss_bytes
                .iter()
                .max()
                .map_or("n/a".to_owned(), |b| mb(*b));
            let _ = writeln!(
                out,
                "| `{}` | {} | {} | {} | {} | {} | {rss} |",
                u.id,
                u.functions,
                ms(p),
                ms(s),
                pct(s, p),
                ms(mean_u64(&u.plain.smt_ms).unwrap_or(0.0))
            );
        }
        out.push('\n');
    }
    out
}
