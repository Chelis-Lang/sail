#!/usr/bin/env bash
# Exercise the same message guard used by hooks and CI.
set -euo pipefail
scratch="$(mktemp -d)"
trap 'rm -rf "$scratch"' EXIT
check() {
  local expected="$1" message="$2" result=0
  printf '%s\n' "$message" > "$scratch/message"
  bash scripts/check-ai-markers.sh message "$scratch/message" > "$scratch/output" 2>&1 || result=$?
  if { [ "$expected" = pass ] && [ "$result" != 0 ]; } ||
     { [ "$expected" = fail ] && [ "$result" = 0 ]; }; then
    printf 'Unexpected guard result (%s): %s\n' "$expected" "$message" >&2
    cat "$scratch/output" >&2
    exit 1
  fi
}
check pass 'Co-authored-by: Jeff Smith <jeff@2ndset.ai>'
check pass 'Co-authored-by: A Human <person@example.com>'
check fail 'Co-authored-by: AI Assistant <person@example.com>'
check fail 'Co-authored-by: LLM <person@example.com>'
check fail 'Co-authored-by: Codex <person@example.com>'
check fail 'Co-authored-by: A Tool <agent@openai.com>'
check fail 'Generated with AI'
check fail 'Generated by GPT-6'
check fail 'Co-authored-by: Human <noreply@anthropic.com>'
# A marker early in a long message: grep must not lose the match to SIGPIPE
# (issue #555's pattern).
check fail "Co-authored-by: Codex <person@example.com>
$(awk 'BEGIN { for (i = 0; i < 100000; i++) print "an ordinary line of the commit message body" }')"
check pass "$(awk 'BEGIN { for (i = 0; i < 100000; i++) print "an ordinary line of the commit message body" }')"
check pass '# only a comment line'
# An unreadable message file is an error, never a clean message.
result=0
bash scripts/check-ai-markers.sh message "$scratch/missing" > "$scratch/output" 2>&1 || result=$?
[ "$result" = 2 ] || { printf 'Unreadable message: status %s, expected 2\n' "$result" >&2; exit 1; }
printf 'authorship message regressions: 13 passed\n'
